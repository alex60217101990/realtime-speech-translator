// Simplex 3D noise — port of the Perlin Simplex variant used by
// the codepen "Swarm [Magnetic Field recreation]"
// (ImagineProgramming/LpOJzM). Self-contained, no external deps.
//
// The particle overlay (sphere.go) samples it with opposite z
// signs for x vs y, producing a curl-like rotational field — the
// "magnetic" look.

const (
	noiseF3 = 1.0 / 3.0
	noiseG3 = 1.0 / 6.0
)

type simplexNoise struct {
	perm  [512]int
	gradP [512][3]float64
}

